import { useEffect, useRef } from 'react'
import gsap from 'gsap'

const ARCHIVE_DATA = [
  { id: '01', title: 'FLUID_LOGIC', tech: 'GSAP / WEBGL', spec: 'SAMPLING RATE: 120HZ / FRICTION: 0.05 / TENSION: 1.2', desc: 'A DEEP STUDY ON LIQUID TYPOGRAPHY. MAPPING MATHEMATICAL WAVE FUNCTIONS TO INDIVIDUAL GLYPH PATHS.' },
  { id: '02', title: 'NEURAL_TYPE', tech: 'REACT / AI', spec: 'LATENCY: 12MS / CORE: TENSOR_V4 / STABILITY: 99%', desc: 'INTERACTIVE TEXT GENERATED BY NEURAL NETWORKS, REACTING TO USER SENTIMENT THROUGH CURSOR VELOCITY.' },
  { id: '03', title: 'GRAVITY_VOID', tech: 'PHYSICS / SCSS', spec: 'MASS: 50KG / GRAVITY: -9.8 / BOUNCE: 0.8', desc: 'EXPLORING THE ABSENCE OF GRAVITY IN UI. ELEMENTS FLOAT AND COLLIDE BASED ON MAC-OS TRACKPAD GESTURES.' },
  { id: '04', title: 'BIT_STREAM', tech: 'MOTION', spec: 'BITRATE: 50MBPS / REFRESH: 240FPS', desc: 'VISUALIZING RAW DATA STREAMS AS KINETIC CHARACTERS. EVERY PIXEL IS A BIT OF INFORMATION.' }
]

export default function Experiments({ activeExp, setActiveId, splitText }: any) {
  const scrollRef = useRef<HTMLDivElement>(null)

  useEffect(() => {
    gsap.fromTo('.work-item', 
      { x: 100, opacity: 0 }, 
      { x: 0, opacity: 1, duration: 1, stagger: 0.1, ease: 'power4.out' }
    )
  }, [])

  return (
    <section id="experiments" className="list-section">
      <div className="section-label reveal">DATABASE_INDEX / EXPERIMENTS</div>
      <div className="works-list" ref={scrollRef}>
        {ARCHIVE_DATA.map((item, i) => (
          <div 
            key={i} 
            className={`work-item ${activeExp === i ? 'active' : ''}`}
            onClick={() => setActiveId(activeExp === i ? null : i)}
          >
            <div className="work-header">
              <span className={`work-id ${activeExp === i ? 'on' : ''}`}>{item.id}</span>
              <h2 className="work-title">{item.title}</h2>
              <span className={`toggle-indicator ${activeExp === i ? 'on' : ''}`}>
                {activeExp === i ? '[ - ]' : '[ + ]'}
              </span>
            </div>
            <div className="work-reveal-content">
              <div className="work-desc">
                <div className="spec-line" style={{ marginBottom: '20px', color: 'var(--accent)', fontSize: '12px' }}>
                  <span>[ SYSTEM_PROTOCOL ]</span> {item.spec}
                </div>
                {splitText(item.desc, "desc-char")}
              </div>
            </div>
          </div>
        ))}
      </div>
    </section>
  )
}
